export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_GAP = 1;

export type Glyph = Uint8Array; // 7 rows, bit (4-x) set when pixel on

function compile(rows: string[]): Glyph {
  const g = new Uint8Array(GLYPH_H);
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] ?? "";
    let bits = 0;
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === "#") bits |= 1 << (GLYPH_W - 1 - x);
    g[y] = bits;
  }
  return g;
}

const GLYPHS = new Map<string, Glyph>();
for (const [ch, rows] of Object.entries(RAW)) GLYPHS.set(ch, compile(rows));
const ICON_GLYPHS = new Map<string, Glyph>();
for (const [name, rows] of Object.entries(ICONS)) ICON_GLYPHS.set(name, compile(rows));

const FALLBACK = compile(["#####", "#   #", "# # #", "#  ##", "# # #", "#   #", "#####"]);

export function glyphFor(ch: string): Glyph {
  return GLYPHS.get(ch) ?? GLYPHS.get(ch.normalize("NFD").replace(/[̀-ͯ]/g, "")) ?? FALLBACK;
}

export function iconGlyph(name: string): Glyph | undefined {
  return ICON_GLYPHS.get(name);
}

/** Pixel width of a string at scale 1 (no trailing gap). */
export function measure(text: string, scale = 1): number {
  const n = Array.from(text).length;
  if (n === 0) return 0;
  return (n * GLYPH_W + (n - 1) * GLYPH_GAP) * scale;
}
